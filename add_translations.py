def read_file(filepath):
    """Read the ai-bullets.ts file"""
    with open(filepath, 'r', encoding='utf-8') as f:
        return f.read()

def write_file(filepath, content):
    """Write the ai-bullets.ts file"""
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)

def format_industry_block(industry, templates, indent=4):
    """Format an industry block in TypeScript"""
    spaces = ' ' * indent
    lines = []
    lines.append(f'{spaces}{industry}: {{')

    for level in ['entry', 'mid', 'senior', 'lead']:
        bullets = templates[level]
        lines.append(f'{spaces}  {level}: [')
        for bullet in bullets:
            # Escape single quotes properly
            bullet_escaped = bullet.replace("'", "\\'")
            lines.append(f"{spaces}    '{bullet_escaped}',")
        lines.append(f'{spaces}  ],')

    lines.append(f'{spaces}}},')
    return '\n'.join(lines)

