function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function rand(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function hydrate(template: string, company: string): string {
  const small = rand(3, 18);
  const medium = rand(small + 5, small + 35);
  const dollars = rand(1, 20) * 50;
  const dollars2 = dollars + rand(2, 30) * 50;

  return template
    .replace(/\{company\}/g, company || 'the organisation')
    .replace(/\{stack\}/g, pick(STACKS))
    .replace(/\{component\}/g, pick(COMPONENTS))
    .replace(/\{feature\}/g, pick(FEATURES))
    .replace(/\{product\}/g, pick(PRODUCTS))
    .replace(/\{process\}/g, pick(PROCESSES))
    .replace(/\{initiative\}/g, pick(INITIATIVES))
    .replace(/\{setting\}/g, pick(SETTINGS))
    .replace(/\{specialty\}/g, pick(SPECIALTIES))
    .replace(/\{practice\}/g, pick(PRACTICES))
    .replace(/\{count3\}/g, String(rand(2, 6)))
    .replace(/\{count2\}/g, String(medium))
    .replace(/\{count\}/g, String(small))
    .replace(/\{pct2\}/g, String(rand(10, 30)))
    .replace(/\{pct\}/g, String(rand(20, 65)))
    .replace(/\{dollars2\}/g, String(dollars2))
    .replace(/\{dollars\}/g, String(dollars))
    .replace(/\{months\}/g, String(rand(3, 18)))
    .replace(/\{days\}/g, String(rand(2, 14)))
    .replace(/\{years\}/g, String(rand(2, 7)));
}

// ─── Fisher-Yates shuffle ─────────────────────────────────────────────────────
function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * Randomly pick 3–5 bullet points for a given industry + level + locale.
 * Each supported locale has its own complete template matrix.
 *
 * When `sourceDescription` already contains bullets, those are treated as
 * canonical and returned unchanged (fact-lock). Invented hospitality/tech
 * duties must not replace real user content just because the UI locale changed.
 */
export function generateBulletsOffline(
  industry: BulletIndustry,
  level: BulletLevel,
  company: string,
  locale: Locale = 'en',
  sourceDescription?: string,
): string {
  const sourceLines = (sourceDescription || '')
    .split(/\r?\n/)
    .map((line) => line.replace(/^[•\-\*\u2022]\s*/, '').trim())
    .filter(Boolean);
  if (sourceLines.length > 0) {
    return sourceLines.map((line) => `• ${line}`).join('\n');
  }

  const localeTemplates = LOCALE_TEMPLATES[locale] ?? LOCALE_TEMPLATES.en;
  const industrySet = localeTemplates[industry] ?? localeTemplates.general;
  const pool = industrySet[level] ?? industrySet.mid;

  // Randomly select 3–5 bullets (never the same set twice in a row via shuffle)
  const count = rand(3, 5);
  const selected = shuffle(pool).slice(0, count);

  return selected
    .map(t => `• ${hydrate(t, company)}`)
    .join('\n');
}

