function mapIndustryTemplates(blueprint: LocaleBlueprint, industry: BulletIndustry): BulletSet {
  const industryLabel = blueprint.industries[industry];

  return {
    entry: blueprint.levels.entry.map((template) => template.replaceAll('{industry}', industryLabel)),
    mid: blueprint.levels.mid.map((template) => template.replaceAll('{industry}', industryLabel)),
    senior: blueprint.levels.senior.map((template) => template.replaceAll('{industry}', industryLabel)),
    lead: blueprint.levels.lead.map((template) => template.replaceAll('{industry}', industryLabel)),
  };
}

